from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any


class BaseEvaluator(ABC):
    """Abstract base class for all evaluation components.

    Each evaluator receives one benchmark case and the corresponding
    system prediction, then returns a dictionary containing evaluation
    metrics.

    Subclasses must implement the :meth:`evaluate` method.

    Attributes:
        name (str): Identifier name for the evaluator.
    """

    name: str = "base"

    @abstractmethod
    def evaluate(self, gold: Any, prediction: Any) -> dict[str, Any]:
        """Evaluate a prediction against ground truth.

        Args:
            gold: Ground truth data generated by the benchmark dataset.
            prediction: Actual output produced by ResiliMind.

        Returns:
            dict[str, Any]: Dictionary containing evaluator-specific metrics.

        Raises:
            NotImplementedError: If the subclass does not implement this method.
        """
        raise NotImplementedError
