from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any


class BaseEvaluator(ABC):
    """
    Abstract base class for all evaluation components.

    Each evaluator receives one benchmark case and the corresponding
    system prediction, then returns a dictionary containing evaluation
    metrics.

    Subclasses should implement the evaluate method.
    """

    name: str = "base"

    @abstractmethod
    def evaluate(
        self,
        gold: Any,
        prediction: Any,
    ) -> dict[str, Any]:
        """
        Evaluate a prediction against ground truth.

        Args:
            gold:
                Ground truth data generated by benchmark dataset.

            prediction:
                Actual output produced by ResiliMind.

        Returns:
            Dictionary containing evaluator-specific metrics.
        """
        raise NotImplementedError
