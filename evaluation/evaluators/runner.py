from __future__ import annotations

import logging
from collections.abc import Iterable, Sequence
from typing import Any

from evaluation.evaluators.base import BaseEvaluator
from evaluation.schemas import CaseEvaluationResult, EvaluationCase, EvaluationSummary

logger = logging.getLogger(__name__)


class EvaluationRunner:
    """Main coordinator for the ResiliMind evaluation pipeline.

    The runner is responsible for:
        - Executing multiple evaluation modules.
        - Passing ground-truth and generated predictions.
        - Collecting per-case evaluation metrics.
        - Handling evaluator failures without stopping the benchmark.
        - Preparing results for later aggregation.

    The runner does not implement evaluation logic itself.
    Each evaluator is responsible for calculating its own metrics.

    Attributes:
        evaluators (Sequence[BaseEvaluator]): Registered evaluation modules.
    """

    def __init__(self, evaluators: Sequence[BaseEvaluator]) -> None:
        """Initialize the evaluation runner.

        Args:
            evaluators: Sequence of registered evaluation modules.

        Raises:
            ValueError: If the evaluators sequence is empty.
        """
        if not evaluators:
            raise ValueError("At least one evaluator is required.")

        self.evaluators = evaluators
        logger.info(
            "[EvaluationRunner] Loaded evaluators: %s",
            [evaluator.name for evaluator in evaluators],
        )

    def evaluate_case(
        self, case: EvaluationCase, prediction: dict[str, Any]
    ) -> CaseEvaluationResult:
        """Evaluate a single benchmark case across all registered evaluators.

        Each evaluator receives:
            - Ground truth annotations from the dataset.
            - The complete workflow output generated by ResiliMind.

        If an evaluator fails, the error is recorded instead of terminating
        the entire evaluation process.

        Args:
            case: Benchmark case containing input and gold labels.
            prediction: Generated workflow output dictionary.

        Returns:
            CaseEvaluationResult: Evaluation results and per-evaluator metrics
                for the given case.
        """
        metrics = {}
        logger.info("[EvaluationRunner] Evaluating case %s", case.case_id)

        for evaluator in self.evaluators:
            try:
                metrics[evaluator.name] = evaluator.evaluate(
                    gold=case.gold,
                    prediction=prediction,
                )
            except Exception as exc:
                logger.exception(
                    "[EvaluationRunner] Evaluator '%s' failed for case %s",
                    evaluator.name,
                    case.case_id,
                )
                metrics[evaluator.name] = {"error": str(exc)}

        return CaseEvaluationResult(case_id=case.case_id, metrics=metrics)

    def evaluate_dataset(
        self,
        cases: Iterable[EvaluationCase],
        predictions: dict[str, dict[str, Any]],
    ) -> list[CaseEvaluationResult]:
        """Evaluate a complete benchmark dataset.

        Args:
            cases: Iterable of benchmark cases.
            predictions: Mapping from case IDs to generated workflow outputs.

        Returns:
            list[CaseEvaluationResult]: Per-case evaluation results for all processed cases.
        """
        results = []
        case_list = list(cases)

        logger.info(
            "[EvaluationRunner] Starting dataset evaluation with %d cases",
            len(case_list),
        )

        for index, case in enumerate(case_list, start=1):
            logger.info(
                "[EvaluationRunner] Processing %d/%d: %s",
                index,
                len(case_list),
                case.case_id,
            )
            prediction = predictions.get(case.case_id, {})
            result = self.evaluate_case(case=case, prediction=prediction)
            results.append(result)

        logger.info("[EvaluationRunner] Dataset evaluation completed.")
        return results

    def summarize(self, results: Sequence[CaseEvaluationResult]) -> EvaluationSummary:
        """Group per-case metrics by evaluator name.

        This method intentionally does not calculate final statistical metrics
        because different evaluators require different aggregation strategies
        (e.g., classification metrics vs. regression metrics vs. LLM judge scores).

        Args:
            results: Sequence of per-case evaluation results.

        Returns:
            EvaluationSummary: Aggregated summary containing total dataset size
                and metrics grouped by evaluator name.

        Raises:
            ValueError: If the input results sequence is empty.
        """
        if not results:
            raise ValueError("Cannot summarize empty results.")

        grouped = {}

        for result in results:
            for evaluator_name, metrics in result.metrics.items():
                grouped.setdefault(evaluator_name, []).append(metrics)

        return EvaluationSummary(dataset_size=len(results), evaluators=grouped)
