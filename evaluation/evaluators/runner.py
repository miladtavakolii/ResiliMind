from __future__ import annotations

import logging
from collections.abc import Iterable
from typing import Any

from evaluation.evaluators.base import BaseEvaluator
from evaluation.schemas import EvaluationCase
from evaluation.schemas.evaluation_result import (
    CaseEvaluationResult,
    EvaluationSummary,
)


logger = logging.getLogger(__name__)


class EvaluationRunner:
    """
    Main coordinator for the ResiliMind evaluation pipeline.

    The runner is responsible for:

    - Executing multiple evaluation modules.
    - Passing ground-truth and generated predictions.
    - Collecting per-case evaluation metrics.
    - Handling evaluator failures without stopping the benchmark.
    - Preparing results for later aggregation.

    The runner does not implement evaluation logic itself.
    Each evaluator is responsible for calculating its own metrics.
    """

    def __init__(
        self,
        evaluators: list[BaseEvaluator],
    ) -> None:
        """
        Initialize evaluation runner.

        Args:
            evaluators:
                Registered evaluation modules.
        """

        if not evaluators:
            raise ValueError(
                "At least one evaluator is required."
            )

        self.evaluators = evaluators

        logger.info(
            "[EvaluationRunner] Loaded evaluators: %s",
            [
                evaluator.name
                for evaluator in evaluators
            ],
        )


    def evaluate_case(
        self,
        case: EvaluationCase,
        prediction: dict[str, Any],
    ) -> CaseEvaluationResult:
        """
        Evaluate a single benchmark case.

        Each evaluator receives:

        - Ground truth annotations from the dataset.
        - The complete workflow output generated by ResiliMind.

        If an evaluator fails, the error is stored instead
        of stopping the complete evaluation process.

        Args:
            case:
                Benchmark case containing input and gold labels.

            prediction:
                Generated workflow output.

        Returns:
            Evaluation metrics for the given case.
        """

        metrics: dict[str, Any] = {}

        logger.info(
            "[EvaluationRunner] Evaluating case %s",
            case.case_id,
        )

        for evaluator in self.evaluators:

            try:
                metrics[evaluator.name] = (
                    evaluator.evaluate(
                        gold=case.gold,
                        prediction=prediction,
                    )
                )

            except Exception as exc:

                logger.exception(
                    "[EvaluationRunner] Evaluator '%s' failed "
                    "for case %s",
                    evaluator.name,
                    case.case_id,
                )

                metrics[evaluator.name] = {
                    "error": str(exc),
                }


        return CaseEvaluationResult(
            case_id=case.case_id,
            metrics=metrics,
        )


    def evaluate_dataset(
        self,
        cases: Iterable[EvaluationCase],
        predictions: dict[str, dict[str, Any]],
    ) -> list[CaseEvaluationResult]:
        """
        Evaluate a complete benchmark dataset.

        Args:
            cases:
                Iterable of benchmark cases.

            predictions:
                Mapping between case IDs and generated outputs.

        Returns:
            List containing evaluation results for every case.
        """

        results: list[CaseEvaluationResult] = []

        cases = list(cases)

        logger.info(
            "[EvaluationRunner] Starting dataset evaluation "
            "with %d cases",
            len(cases),
        )

        for index, case in enumerate(
            cases,
            start=1,
        ):

            logger.info(
                "[EvaluationRunner] Processing %d/%d: %s",
                index,
                len(cases),
                case.case_id,
            )

            prediction = predictions.get(
                case.case_id,
                {},
            )

            result = self.evaluate_case(
                case=case,
                prediction=prediction,
            )

            results.append(result)


        logger.info(
            "[EvaluationRunner] Dataset evaluation completed."
        )

        return results


    def summarize(
        self,
        results: list[CaseEvaluationResult],
    ) -> EvaluationSummary:
        """
        Collect per-case metrics.

        This method intentionally does not calculate final
        statistical metrics because different evaluators require
        different aggregation strategies.

        Examples:

        - Classification metrics:
            Accuracy, Precision, Recall, F1

        - Regression metrics:
            MAE, RMSE

        - LLM Judge metrics:
            Mean score per dimension


        Args:
            results:
                Per-case evaluation results.

        Returns:
            Raw grouped evaluation data.
        """

        if not results:
            raise ValueError(
                "Cannot summarize empty results."
            )

        grouped: dict[str, list[Any]] = {}

        for result in results:

            for evaluator_name, metrics in (
                result.metrics.items()
            ):

                grouped.setdefault(
                    evaluator_name,
                    [],
                ).append(metrics)


        return EvaluationSummary(
            dataset_size=len(results),
            evaluators=grouped,
        )
