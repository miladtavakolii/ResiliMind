from __future__ import annotations

import argparse
import json
import logging
import os
from pathlib import Path
from typing import Any
import time
from dotenv import load_dotenv

from google import genai
from google.genai import types
from pydantic import BaseModel, ConfigDict, Field

from evaluation.schemas import EvaluationCase
from evaluation.generators.validators import validate_case

logger = logging.getLogger(__name__)

PROJECT_ROOT = Path(__file__).resolve().parents[2]

DEFAULT_PROMPT_PATH = (
    PROJECT_ROOT
    / "evaluation"
    / "prompts"
    / "scenario_renderer.txt"
)

DEFAULT_INPUT_PATH = (
    PROJECT_ROOT
    / "evaluation"
    / "datasets"
    / "v1"
    / "scenarios.jsonl"
)

DEFAULT_OUTPUT_PATH = (
    PROJECT_ROOT
    / "evaluation"
    / "datasets"
    / "v1"
    / "cases.jsonl"
)


class RenderedMessage(BaseModel):
    """Represent a single generated user message."""

    model_config = ConfigDict(extra="forbid")

    content: str = Field(min_length=1)


class RenderedEvidence(BaseModel):
    """Represent evidence associated with a generated signal."""

    model_config = ConfigDict(extra="forbid")

    node_id: str
    evidence: str = Field(min_length=1)
    message_index: int = Field(ge=0)


class ScenarioRenderOutput(BaseModel):
    """Represent the structured output generated by Gemini.

    The model is restricted to producing natural-language user messages and
    evidence spans. Ground-truth safety, extraction, assessment, and routing
    information remains controlled by the deterministic benchmark generator.
    """

    model_config = ConfigDict(extra="forbid")

    messages: list[RenderedMessage] = Field(min_length=1)
    evidence: list[RenderedEvidence] = Field(default_factory=list)


class ScenarioRenderer:
    """Render latent evaluation scenarios into natural Persian conversations.

    Gemini is used only as a natural-language realization model. It does not
    determine the benchmark ground truth and cannot modify the safety,
    extraction, assessment, or routing annotations.

    The renderer validates the generated message count and verifies that every
    evidence span is an exact substring of its referenced user message.
    """

    VERSION = "1.0.0"

    def __init__(
        self,
        *,
        model_name: str = "gemini-2.5-flash",
        api_key: str | None = None,
        temperature: float = 0.7,
        prompt_path: Path = DEFAULT_PROMPT_PATH,
        max_retries: int = 3,
        retry_delay: float = 2.0,
        request_delay: float = 1.0,
    ) -> None:
        """Initialize the Gemini scenario renderer.

        Args:
            model_name: Gemini model used to render latent scenarios.
            api_key: Gemini API key. If omitted, ``GEMINI_API_KEY`` is used.
            temperature: Sampling temperature for natural-language generation.
            prompt_path: Path to the system rendering prompt.
            max_retries: Maximum number of retries after an API failure.
            retry_delay: Initial delay in seconds before retrying a failed request.
            request_delay: Delay in seconds between consecutive API requests.

        Raises:
            ValueError: If the Gemini API key is not configured or any timing
                parameter is invalid.
            FileNotFoundError: If the prompt file does not exist.
        """
        if max_retries < 0:
            raise ValueError("max_retries must be >= 0")

        if retry_delay < 0:
            raise ValueError("retry_delay must be >= 0")

        if request_delay < 0:
            raise ValueError("request_delay must be >= 0")

        self.model_name = model_name
        self.temperature = temperature
        self.prompt_path = prompt_path
        self.max_retries = max_retries
        self.retry_delay = retry_delay
        self.request_delay = request_delay

        api_key = api_key or os.getenv("GEMINI_API_KEY")

        if not api_key:
            raise ValueError(
                "Gemini API key is not configured. "
                "Set GEMINI_API_KEY in the environment."
            )

        self.client = genai.Client(
            api_key=api_key,
        )

        self.system_prompt = self._load_prompt()

    def _load_prompt(self) -> str:
        """Load the rendering system prompt from disk.

        Returns:
            Prompt text used to instruct Gemini.
        """
        if not self.prompt_path.exists():
            raise FileNotFoundError(
                f"Rendering prompt not found: {self.prompt_path}"
            )

        return self.prompt_path.read_text(
            encoding="utf-8",
        )

    def _generate(
        self,
        *,
        prompt: str,
    ) -> ScenarioRenderOutput:
        """Generate structured scenario content with automatic retries.

        The request is retried after API failures using exponential backoff.
        """

        last_error: Exception | None = None

        for attempt in range(self.max_retries + 1):
            try:
                response = self.client.models.generate_content(
                    model=self.model_name,
                    contents=[
                        self.system_prompt,
                        prompt,
                    ],
                    config=types.GenerateContentConfig(
                        temperature=self.temperature,
                        response_mime_type="application/json",
                        response_schema=ScenarioRenderOutput,
                    ),
                )

                if not response.text:
                    raise ValueError(
                        "Gemini returned an empty response"
                    )

                return ScenarioRenderOutput.model_validate_json(
                    response.text
                )

            except Exception as exc:
                last_error = exc

                if attempt >= self.max_retries:
                    break

                delay = self.retry_delay * (2 ** attempt)

                logger.warning(
                    "Gemini request failed "
                    "(attempt %d/%d): %s. Retrying in %.1f seconds...",
                    attempt + 1,
                    self.max_retries + 1,
                    exc,
                    delay,
                )

                time.sleep(delay)

        raise RuntimeError(
            f"Gemini request failed after "
            f"{self.max_retries + 1} attempts"
        ) from last_error

    def render(
        self,
        case: EvaluationCase,
    ) -> EvaluationCase:
        """Render one latent scenario into a natural-language conversation."""

        prompt = self._build_user_prompt(case)

        rendered = self._generate(
            prompt=prompt,
        )

        self._validate_rendered_output(
            case=case,
            output=rendered,
        )

        case.input.messages = [
            message.content
            for message in rendered.messages
        ]

        self._attach_evidence(
            case=case,
            evidence=rendered.evidence,
        )

        return case
        
    def _build_user_prompt(
        self,
        case: EvaluationCase,
    ) -> str:
        """Build the Gemini prompt from a latent evaluation scenario.

        Numerical rubric values are intentionally excluded from the prompt.
        The model receives only the semantic information necessary to express
        the latent scenario naturally.

        Args:
            case: Evaluation case being rendered.

        Returns:
            JSON-formatted scenario description for Gemini.
        """
        signals = [
            {
                "concept": signal.node_id,
                "polarity": signal.detected_signal,
            }
            for signal in case.gold.extraction.active_signals
        ]

        assessment_levels = []

        for assessment in case.gold.assessment.assessments:
            total = assessment.total_score

            if total >= 70:
                level = "relatively strong resilience"
            elif total >= 40:
                level = "moderate or mixed resilience"
            else:
                level = "low resilience or significant difficulty"

            assessment_levels.append(
                {
                    "concept": assessment.node_id,
                    "level": level,
                }
            )

        scenario = {
            "domain": case.scenario.domain,
            "difficulty": case.scenario.difficulty,
            "case_type": case.scenario.case_type,
            "turn_count": case.scenario.turn_count,
            "safety_category": case.gold.safety.risk_category,
            "signals": signals,
            "assessment_levels": assessment_levels,
        }

        return json.dumps(
            scenario,
            ensure_ascii=False,
            indent=2,
        )

    def _validate_rendered_output(
        self,
        *,
        case: EvaluationCase,
        output: ScenarioRenderOutput,
    ) -> None:
        """Validate Gemini output against the latent scenario.

        Args:
            case: Original evaluation case.
            output: Structured output returned by Gemini.

        Raises:
            ValueError: If message count or evidence alignment is invalid.
        """
        expected_turns = case.scenario.turn_count

        if len(output.messages) != expected_turns:
            raise ValueError(
                f"{case.case_id}: expected {expected_turns} messages, "
                f"got {len(output.messages)}"
            )

        signal_node_ids = {
            signal.node_id
            for signal in case.gold.extraction.active_signals
        }

        evidence_node_ids = {
            item.node_id
            for item in output.evidence
        }

        unexpected_nodes = evidence_node_ids - signal_node_ids

        if unexpected_nodes:
            raise ValueError(
                f"{case.case_id}: evidence returned for unknown signals: "
                f"{sorted(unexpected_nodes)}"
            )

        for item in output.evidence:
            if item.message_index >= len(output.messages):
                raise ValueError(
                    f"{case.case_id}: evidence for {item.node_id} "
                    f"references invalid message index "
                    f"{item.message_index}"
                )

            message = output.messages[
                item.message_index
            ].content

            if item.evidence not in message:
                raise ValueError(
                    f"{case.case_id}: evidence for {item.node_id} "
                    "is not an exact substring of the referenced message"
                )

        missing_evidence = signal_node_ids - evidence_node_ids

        if missing_evidence:
            raise ValueError(
                f"{case.case_id}: missing evidence for signals: "
                f"{sorted(missing_evidence)}"
            )

    def _attach_evidence(
        self,
        *,
        case: EvaluationCase,
        evidence: list[RenderedEvidence],
    ) -> None:
        """Attach validated evidence spans to their corresponding signals.

        Args:
            case: Evaluation case being updated.
            evidence: Validated evidence generated by Gemini.

        Raises:
            ValueError: If an expected signal does not have evidence.
        """
        evidence_by_node = {
            item.node_id: item
            for item in evidence
        }

        for signal in case.gold.extraction.active_signals:
            item = evidence_by_node.get(signal.node_id)

            if item is None:
                raise ValueError(
                    f"{case.case_id}: missing evidence for "
                    f"{signal.node_id}"
                )

            signal.evidence = item.evidence
            signal.evidence_message_index = item.message_index

    def render_dataset(
        self,
        cases: list[EvaluationCase],
        *,
        skip_failures: bool = False,
    ) -> list[EvaluationCase]:
        """Render all cases in a dataset."""

        rendered_cases: list[EvaluationCase] = []

        for index, case in enumerate(cases, start=1):
            logger.info(
                "Rendering case %d/%d: %s",
                index,
                len(cases),
                case.case_id,
            )

            try:
                rendered_case = self.render(case)

                rendered_cases.append(
                    rendered_case,
                )

            except Exception:
                logger.exception(
                    "Failed to render case %s",
                    case.case_id,
                )

                if not skip_failures:
                    raise

            if index < len(cases):
                logger.info(
                    "Sleeping %.1f seconds before next request...",
                    self.request_delay,
                )
                time.sleep(self.request_delay)

        return rendered_cases

def load_cases(
    input_path: Path,
) -> list[EvaluationCase]:
    """Load evaluation scenarios from a JSONL file.

    Args:
        input_path: Path to the source JSONL dataset.

    Returns:
        Parsed evaluation cases.

    Raises:
        FileNotFoundError: If the input dataset does not exist.
        ValueError: If a dataset record is invalid.
    """
    if not input_path.exists():
        raise FileNotFoundError(
            f"Input dataset not found: {input_path}"
        )

    cases: list[EvaluationCase] = []

    with input_path.open(
        "r",
        encoding="utf-8",
    ) as file:
        for line_number, line in enumerate(
            file,
            start=1,
        ):
            line = line.strip()

            if not line:
                continue

            try:
                data: dict[str, Any] = json.loads(line)

                cases.append(
                    EvaluationCase.model_validate(data)
                )

            except Exception as exc:
                raise ValueError(
                    f"Invalid evaluation case at line "
                    f"{line_number}: {exc}"
                ) from exc

    return cases


def write_cases(
    cases: list[EvaluationCase],
    output_path: Path,
) -> None:
    """Write rendered evaluation cases to a JSONL file.

    Args:
        cases: Evaluation cases to serialize.
        output_path: Destination JSONL file.
    """
    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with output_path.open(
        "w",
        encoding="utf-8",
    ) as file:
        for case in cases:
            file.write(
                json.dumps(
                    case.model_dump(),
                    ensure_ascii=False,
                )
                + "\n"
            )


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments for the scenario renderer.

    Returns:
        Parsed command-line arguments.
    """
    parser = argparse.ArgumentParser(
        description=(
            "Render latent ResiliMind evaluation scenarios "
            "into natural-language Persian conversations."
        )
    )

    parser.add_argument(
        "--input",
        type=Path,
        default=DEFAULT_INPUT_PATH,
        help="Path to the latent scenarios JSONL file.",
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT_PATH,
        help="Path for the rendered cases JSONL file.",
    )

    parser.add_argument(
        "--model",
        type=str,
        default=os.getenv(
            "GEMINI_MODEL",
            "gemini-2.5-flash",
        ),
        help="Gemini model used for scenario rendering.",
    )

    parser.add_argument(
        "--temperature",
        type=float,
        default=0.7,
        help="Sampling temperature.",
    )

    parser.add_argument(
        "--prompt",
        type=Path,
        default=DEFAULT_PROMPT_PATH,
        help="Path to the rendering system prompt.",
    )

    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Render only the first N cases.",
    )

    parser.add_argument(
        "--skip-failures",
        action="store_true",
        help="Skip cases that fail rendering.",
    )

    parser.add_argument(
        "--max-retries",
        type=int,
        default=3,
        help="Maximum number of retries after an API failure.",
    )

    parser.add_argument(
        "--retry-delay",
        type=float,
        default=2.0,
        help="Initial retry delay in seconds.",
    )

    parser.add_argument(
        "--request-delay",
        type=float,
        default=1.0,
        help="Delay between consecutive API requests in seconds.",
    )

    return parser.parse_args()


def main() -> None:
    """Run the complete scenario rendering pipeline."""
    load_dotenv()
    args = parse_args()

    cases = load_cases(
        args.input,
    )

    if args.limit is not None:
        if args.limit <= 0:
            raise ValueError(
                "--limit must be greater than zero"
            )

        cases = cases[:args.limit]

    renderer = ScenarioRenderer(
        model_name=args.model,
        temperature=args.temperature,
        prompt_path=args.prompt,
        max_retries=args.max_retries,
        retry_delay=args.retry_delay,
        request_delay=args.request_delay,
    )

    rendered_cases = renderer.render_dataset(
        cases,
        skip_failures=args.skip_failures,
    )

    write_cases(
        rendered_cases,
        args.output,
    )

    print(
        f"Rendered {len(rendered_cases)} cases."
    )
    print(
        f"Dataset: {args.output}"
    )
    print(
        f"Model: {args.model}"
    )


if __name__ == "__main__":
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )

    main()
