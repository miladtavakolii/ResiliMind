from __future__ import annotations

import argparse
import json
import logging
import os
from pathlib import Path
import time
from dotenv import load_dotenv
import re
from types import Any

from google import genai
from google.genai import types
from pydantic import BaseModel, Field

from evaluation.schemas import EvaluationCase
from evaluation.generators.validators import validate_dataset

logger = logging.getLogger(__name__)

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PROMPT_PATH = PROJECT_ROOT / "evaluation" / "prompts" / "scenario_renderer.txt"
DEFAULT_INPUT_PATH = PROJECT_ROOT / "evaluation" / "datasets" / "v1" / "scenarios.jsonl"
DEFAULT_OUTPUT_PATH = PROJECT_ROOT / "evaluation" / "datasets" / "v1" / "cases.jsonl"
GRAPH_PATH = PROJECT_ROOT / "src" / "resilimind" / "assets" / "final_resilience_graph.json"

EVIDENCE_PATTERN = re.compile(
    r"\[\[EVIDENCE:(?P<node_id>[A-Za-z0-9_]+)\]\]"
    r"(?P<text>.*?)"
    r"\[\[/EVIDENCE:(?P=node_id)\]\]",
    re.DOTALL,
)

class RenderedMessage(BaseModel):
    """Represent a single generated user message.

    Attributes:
        content (str): The natural language text content of the message.
    """

    content: str = Field(min_length=1)


class ScenarioRenderOutput(BaseModel):
    """Represent the structured output generated by Gemini.

    Attributes:
        messages (list[RenderedMessage]): List of rendered user messages.
        evidence (list[RenderedEvidence]): Extracted evidence items corresponding
            to active resilience signals.
    """

    messages: list[RenderedMessage] = Field(min_length=1)


class ScenarioRenderer:
    """Render latent evaluation scenarios into natural Persian conversations.

    Attributes:
        VERSION (str): Renderer component version.
        model_name (str): Gemini model identifier.
        temperature (float): Generation temperature.
        prompt_path (Path): Path to the system rendering prompt template.
        max_retries (int): Number of retries on API failure.
        retry_delay (float): Initial backoff delay between retries.
        request_delay (float): Politeness delay between successive scenario generations.
        client (genai.Client): Initialized Google GenAI SDK client.
        system_prompt (str): Loaded rendering prompt instructions.
    """

    VERSION: str = "1.0.0"

    def __init__(
        self,
        *,
        model_name: str = "gemini-2.5-flash",
        api_key: str | None = None,
        temperature: float = 0.7,
        prompt_path: Path = DEFAULT_PROMPT_PATH,
        max_retries: int = 3,
        retry_delay: float = 2.0,
        request_delay: float = 1.0,
    ) -> None:
        """Initialize the scenario renderer.

        Args:
            model_name: Gemini model name for natural language generation.
            api_key: Optional Gemini API key. If omitted, fetched from GEMINI_API_KEY.
            temperature: Sampling temperature for generation diversity.
            prompt_path: Path to the rendering prompt text file.
            max_retries: Maximum retry attempts on API errors.
            retry_delay: Base delay in seconds for exponential backoff.
            request_delay: Delay in seconds between API calls to avoid rate limits.

        Raises:
            ValueError: If delays or retries are negative, or if the API key is unset.
        """
        if max_retries < 0:
            raise ValueError("max_retries must be >= 0")
        if retry_delay < 0:
            raise ValueError("retry_delay must be >= 0")
        if request_delay < 0:
            raise ValueError("request_delay must be >= 0")

        self.model_name = model_name
        self.temperature = temperature
        self.prompt_path = prompt_path
        self.max_retries = max_retries
        self.retry_delay = retry_delay
        self.request_delay = request_delay

        api_key = api_key or os.getenv("GEMINI_API_KEY")
        if not api_key:
            raise ValueError("Gemini API key is not configured. Set GEMINI_API_KEY in the environment.")

        self.client = genai.Client(api_key=api_key)
        self.system_prompt = self._load_prompt()

    def _load_prompt(self) -> str:
        """Load the rendering system prompt from disk.

        Returns:
            str: System prompt text content.

        Raises:
            FileNotFoundError: If the prompt file does not exist.
        """
        if not self.prompt_path.exists():
            raise FileNotFoundError(f"Rendering prompt not found: {self.prompt_path}")
        return self.prompt_path.read_text(encoding="utf-8")

    def _generate(self, *, prompt: str) -> ScenarioRenderOutput:
        """Generate structured scenario content with automatic retries and exponential backoff.

        Args:
            prompt: Structured JSON string representing the latent scenario spec.

        Returns:
            ScenarioRenderOutput: Structured messages and evidence output.

        Raises:
            RuntimeError: If all retry attempts fail.
        """
        last_error = None

        for attempt in range(self.max_retries + 1):
            try:
                response = self.client.models.generate_content(
                    model=self.model_name,
                    contents=[self.system_prompt, prompt],
                    config=types.GenerateContentConfig(
                        temperature=self.temperature,
                        response_mime_type="application/json",
                        response_schema=ScenarioRenderOutput,
                    ),
                )
                if not response.text:
                    raise ValueError("Gemini returned an empty response")

                return ScenarioRenderOutput.model_validate_json(response.text)

            except Exception as exc:
                last_error = exc
                if attempt >= self.max_retries:
                    break

                delay = self.retry_delay * (2**attempt)
                logger.warning(
                    "Gemini request failed (attempt %d/%d): %s. Retrying in %.1f seconds...",
                    attempt + 1,
                    self.max_retries + 1,
                    exc,
                    delay,
                )
                time.sleep(delay)

        raise RuntimeError(f"Gemini request failed after {self.max_retries + 1} attempts") from last_error

    def render(self, case: EvaluationCase) -> EvaluationCase:
        """Render one latent scenario into a natural-language conversation.

        Args:
            case: Evaluation case containing the latent scenario specification.

        Returns:
            EvaluationCase: Updated case with rendered messages and attached evidence.
        """
        prompt = self._build_user_prompt(case)
        rendered = self._generate(prompt=prompt)

        evidence = self._extract_evidence(case, rendered)
        messages = self._clean_messages(rendered.messages)

        self._validate_rendered_output(case=case, messages=messages, evidence=evidence)
        case.input.messages = messages
        self._attach_evidence(case=case, evidence=evidence)

        return case

    def _build_user_prompt(self, case: EvaluationCase) -> str:
        """Build the Gemini prompt from a latent evaluation scenario.

        Args:
            case: Evaluation case to serialize into a generation prompt.

        Returns:
            str: JSON string summarizing scenario characteristics and requirements.
        """
        signals = [
            {"concept": signal.node_id, "polarity": signal.detected_signal}
            for signal in case.gold.extraction.active_signals
        ]

        scenario = {
            "domain": case.scenario.domain,
            "difficulty": case.scenario.difficulty,
            "case_type": case.scenario.case_type,
            "turn_count": case.scenario.turn_count,
            "safety_category": case.gold.safety.risk_category,
            "signals": signals,
              "assessment_profile":{
                "severity": case.scenario.severity_level,
                "frequency": case.scenario.frequency_level,
                "functional": case.scenario.functional_level,
                "coping": case.scenario.coping_level,
            }
        }

        return json.dumps(scenario, ensure_ascii=False, indent=2)

    def _clean_messages(self, messages: list[RenderedMessage]) -> list[str]:
        """Strip evidence annotation markup from rendered messages.

        Replaces evidence markup patterns with their underlying plain-text content
        to produce clean, readable user messages.

        Args:
            messages: List of RenderedMessage instances containing annotated text.

        Returns:
            list[str]: Cleaned message content strings without annotation tags.
        """
        cleaned = []

        for message in messages:
            text = EVIDENCE_PATTERN.sub(
                lambda m: m.group("text"),
                message.content,
            )
            cleaned.append(text)

        return cleaned

    def _extract_evidence(
        self, case: EvaluationCase, output: ScenarioRenderOutput
    ) -> list[dict[str, Any]]:
        """Extract evidence spans from rendered scenario messages based on regex patterns.

        Args:
            case: Target EvaluationCase instance containing gold active signals.
            output: ScenarioRenderOutput containing rendered message objects.

        Returns:
            list[dict[str, Any]]: List of extracted evidence records containing
                node_id, message_index, character span offsets, and raw text.

        Raises:
            ValueError: If an extracted evidence node_id is not part of the expected
                gold active signals for the case.
        """
        expected = {
            signal.node_id
            for signal in case.gold.extraction.active_signals
        }

        extracted = []

        for message_index, message_obj in enumerate(output.messages):
            message = message_obj.content

            for match in EVIDENCE_PATTERN.finditer(message):
                node_id = match.group("node_id")

                if node_id not in expected:
                    raise ValueError(
                        f"{case.case_id}: unexpected evidence node {node_id}"
                    )

                start = match.start("text")
                end = match.end("text")

                extracted.append(
                    {
                        "node_id": node_id,
                        "message_index": message_index,
                        "start": start,
                        "end": end,
                        "evidence": match.group("text"),
                    }
                )

        return extracted

    def _validate_rendered_output(
        self,
        *,
        case: EvaluationCase,
        output: ScenarioRenderOutput,
        evidence: list[dict[str, Any]],
    ) -> None:
        """Validate Gemini output against the latent scenario constraints.

        Args:
            case: EvaluationCase ground-truth specification.
            output: Structured model response to validate.
            evidence: Extracted evidence records containing character span offsets.

        Raises:
            ValueError: If message counts mismatch, unknown signal evidence is returned,
                indices are invalid, or evidence character spans do not match the raw message.
        """
        expected_turns = case.scenario.turn_count
        if len(output.messages) != expected_turns:
            raise ValueError(
                f"{case.case_id}: expected {expected_turns} messages, got {len(output.messages)}"
            )

        signal_node_ids = {
            signal.node_id for signal in case.gold.extraction.active_signals
        }
        evidence_node_ids = {item.node_id for item in output.evidence}

        unexpected_nodes = evidence_node_ids - signal_node_ids
        if unexpected_nodes:
            raise ValueError(
                f"{case.case_id}: evidence returned for unknown signals: {sorted(unexpected_nodes)}"
            )

        extracted_ids = {item["node_id"] for item in evidence}
        if signal_node_ids != extracted_ids:
            raise ValueError(f"{case.case_id}: evidence mismatch")

        for item in evidence:
            message_index = item["message_index"]
            if message_index >= len(output.messages):
                raise ValueError(
                    f"{case.case_id}: invalid message_index {message_index} for {item['node_id']}"
                )

            message_content = output.messages[message_index].content
            extracted = message_content[item["start"] : item["end"]]

            if extracted != item["evidence"]:
                raise ValueError(
                    f"{case.case_id}: invalid evidence span for {item['node_id']}"
                )

        missing_evidence = signal_node_ids - evidence_node_ids
        if missing_evidence:
            raise ValueError(
                f"{case.case_id}: missing evidence for signals: {sorted(missing_evidence)}"
            )

    def _attach_evidence(
        self,
        *,
        case: EvaluationCase,
        evidence: list[dict[str, Any]],
    ) -> None:
        """Attach validated evidence spans to their corresponding gold signals.

        Args:
            case: The evaluation case whose signals will be updated in-place.
            evidence: List of verified evidence records containing offsets and text.

        Raises:
            ValueError: If a required gold signal is missing associated evidence.
        """
        evidence_by_node = {item["node_id"]: item for item in evidence}

        for signal in case.gold.extraction.active_signals:
            item = evidence_by_node.get(signal.node_id)
            if item is None:
                raise ValueError(
                    f"{case.case_id}: missing evidence for {signal.node_id}"
                )

            signal.evidence = item["evidence"]
            signal.evidence_message_index = item["message_index"]
            signal.evidence_start = item["start"]
            signal.evidence_end = item["end"]
    def render_dataset(
        self, cases: list[EvaluationCase], *, skip_failures: bool = False
    ) -> list[EvaluationCase]:
        """Render all cases in a dataset sequentially.

        Args:
            cases: Sequence of evaluation cases to render.
            skip_failures: Whether to bypass individual failures instead of raising.

        Returns:
            list[EvaluationCase]: Successfully rendered evaluation cases.
        """
        rendered_cases = []

        for index, case in enumerate(cases, start=1):
            logger.info("Rendering case %d/%d: %s", index, len(cases), case.case_id)
            try:
                rendered_case = self.render(case)
                rendered_cases.append(rendered_case)
            except Exception:
                logger.exception("Failed to render case %s", case.case_id)
                if not skip_failures:
                    raise

            if index < len(cases):
                logger.info("Sleeping %.1f seconds before next request...", self.request_delay)
                time.sleep(self.request_delay)

        return rendered_cases


def load_cases(input_path: Path) -> list[EvaluationCase]:
    """Load evaluation scenarios from a JSONL file.

    Args:
        input_path: Path to the JSONL input file.

    Returns:
        list[EvaluationCase]: Parsed evaluation cases.

    Raises:
        FileNotFoundError: If the input file is missing.
        ValueError: If line deserialization or schema validation fails.
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Input dataset not found: {input_path}")

    cases: list[EvaluationCase] = []
    with input_path.open("r", encoding="utf-8") as file:
        for line_number, line in enumerate(file, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                cases.append(EvaluationCase.model_validate(json.loads(line)))
            except Exception as exc:
                raise ValueError(f"Invalid evaluation case at line {line_number}: {exc}") from exc

    return cases


def write_cases(cases: list[EvaluationCase], output_path: Path) -> None:
    """Write rendered evaluation cases to a JSONL file.

    Args:
        cases: Sequence of evaluation cases to write.
        output_path: Destination path for the JSONL file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8") as file:
        for case in cases:
            file.write(json.dumps(case.model_dump(), ensure_ascii=False) + "\n")


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments for the scenario renderer.

    Returns:
        argparse.Namespace: Parsed CLI argument namespace.
    """
    parser = argparse.ArgumentParser(
        description="Render latent ResiliMind evaluation scenarios into natural-language Persian conversations."
    )
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT_PATH, help="Path to the latent scenarios JSONL file.")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_PATH, help="Path for the rendered cases JSONL file.")
    parser.add_argument("--model", type=str, default=os.getenv("GEMINI_MODEL", "gemini-2.5-flash"), help="Gemini model used for scenario rendering.")
    parser.add_argument("--temperature", type=float, default=0.7, help="Sampling temperature.")
    parser.add_argument("--prompt", type=Path, default=DEFAULT_PROMPT_PATH, help="Path to the rendering system prompt.")
    parser.add_argument("--limit", type=int, default=None, help="Render only the first N cases.")
    parser.add_argument("--skip-failures", action="store_true", help="Skip cases that fail rendering.")
    parser.add_argument("--max-retries", type=int, default=3, help="Maximum number of retries after an API failure.")
    parser.add_argument("--retry-delay", type=float, default=2.0, help="Initial retry delay in seconds.")
    parser.add_argument("--request-delay", type=float, default=1.0, help="Delay between consecutive API requests in seconds.")
    return parser.parse_args()


def main() -> None:
    """Run the complete scenario rendering pipeline."""
    load_dotenv()
    args = parse_args()

    cases = load_cases(args.input)
    if args.limit is not None:
        if args.limit <= 0:
            raise ValueError("--limit must be greater than zero")
        cases = cases[:args.limit]

    renderer = ScenarioRenderer(
        model_name=args.model,
        temperature=args.temperature,
        prompt_path=args.prompt,
        max_retries=args.max_retries,
        retry_delay=args.retry_delay,
        request_delay=args.request_delay,
    )

    rendered_cases = renderer.render_dataset(cases, skip_failures=args.skip_failures)
    with GRAPH_PATH.open("r", encoding="utf-8") as file:
        graph = json.load(file)

    valid_node_ids = set(graph["nodes"].keys())

    errors = validate_dataset(
        cases,
        valid_node_ids=valid_node_ids,
        require_rendered=True,
    )
    if errors:
        formatted_errors = "\n".join(f"- {error}" for error in errors)
        raise ValueError(
            f"Rendered dataset validation failed:\n{formatted_errors}"
        )
    
    write_cases(rendered_cases, args.output)

    print(f"Rendered {len(rendered_cases)} cases.")
    print(f"Dataset: {args.output}")
    print(f"Model: {args.model}")


if __name__ == "__main__":
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )
    main()
