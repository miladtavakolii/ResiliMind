EVIDENCE_PATTERN = re.compile(
    r"\[\[EVIDENCE:(?P<node_id>[A-Za-z0-9_]+)\]\]"
    r"(?P<text>.*?)"
    r"\[\[/EVIDENCE:(?P=node_id)\]\]",
    re.DOTALL,
)

class RenderedMessage(BaseModel):
    """epresent the structured output generated by Gemini.

    Attributes:
        content (str): The natural language text content of the message.
    """

    content: str = Field(min_length=1)


class ScenarioRenderOutput(BaseModel):
    """Represent the structured output generated by Gemini.

    Attributes:
        messages (list[RenderedMessage]): List of rendered user messages.
    """

    messages: list[RenderedMessage] = Field(min_length=1)

class ScenarioRenderAudit(BaseModel):
    """Semantic validation result for a rendered evaluation case."""

    valid: bool
    missing_target_signals: list[str] = Field(default_factory=list)
    unintended_signal_nodes: list[str] = Field(default_factory=list)
    polarity_errors: list[str] = Field(default_factory=list)
    evidence_issues: list[str] = Field(default_factory=list)
    explanation: str = ""

class ScenarioRenderer:
    """Render latent evaluation scenarios into natural Persian conversations.

    Attributes:
        VERSION (str): Renderer component version.
        model_name (str): Gemini model identifier.
        temperature (float): Generation temperature.
        prompt_path (Path): Path to the system rendering prompt template.
        max_retries (int): Number of retries on API failure.
        retry_delay (float): Initial backoff delay between retries.
        request_delay (float): Politeness delay between successive scenario generations.
        client (genai.Client): Initialized Google GenAI SDK client.
        system_prompt (str): Loaded rendering prompt instructions.
    """

    VERSION: str = "1.0.0"

    def __init__(
        self,
        *,
        model_name: str = "gemini-2.5-flash",
        api_key: str | None = None,
        temperature: float = 0.4,
        prompt_path: Path = DEFAULT_PROMPT_PATH,
        audit_prompt_path: Path = DEFAULT_AUDIT_PROMPT_PATH,
        graph_path: Path = GRAPH_PATH,
        max_retries: int = 3,
        retry_delay: float = 2.0,
        request_delay: float = 1.0,
    ) -> None:
        """Initialize the scenario renderer.

        Args:
            model_name: Gemini model name for natural language generation.
            api_key: Optional Gemini API key. If omitted, fetched from GEMINI_API_KEY.
            temperature: Sampling temperature for generation diversity.
            prompt_path: Path to the rendering prompt text file.
            audit_prompt_path: Path to the audit prompt text file.
            graph_path: Path to the knowledge graph JSON file.
            max_retries: Maximum retry attempts for generation, audit, and validation failures.
            retry_delay: Base delay in seconds for exponential backoff.
            request_delay: Delay in seconds between API calls to avoid rate limits.

        Raises:
            ValueError: If delays or retries are negative, or if the API key is unset.
        """
        if max_retries < 0:
            raise ValueError("max_retries must be >= 0")
        if retry_delay < 0:
            raise ValueError("retry_delay must be >= 0")
        if request_delay < 0:
            raise ValueError("request_delay must be >= 0")

        self.model_name = model_name
        self.temperature = temperature
        self.prompt_path = prompt_path
        self.audit_prompt_path = audit_prompt_path
        self.max_retries = max_retries
        self.retry_delay = retry_delay
        self.request_delay = request_delay
        self.graph_path = Path(graph_path)
        self.graph = self._load_graph()
        self.nodes = self._load_nodes()

        api_key = api_key or os.getenv("GEMINI_API_KEY")
        if not api_key:
            raise ValueError("Gemini API key is not configured. Set GEMINI_API_KEY in the environment.")

        self.client = genai.Client(api_key=api_key)
        self.system_prompt = self._load_prompt()
        self.audit_prompt = self._load_audit_prompt()

    def _load_graph(self) -> dict[str, Any]:
        """Load and validate the knowledge graph from disk.

        Returns:
            dict[str, Any]: Parsed knowledge graph containing validated nodes.

        Raises:
            FileNotFoundError: If the knowledge graph file does not exist.
            ValueError: If the JSON payload lacks a valid top-level 'nodes' dictionary.
        """
        if not self.graph_path.exists():
            raise FileNotFoundError(f"Knowledge graph not found: {self.graph_path}")

        with self.graph_path.open("r", encoding="utf-8") as file:
            graph = json.load(file)

        if "nodes" not in graph or not isinstance(graph["nodes"], dict):
            raise ValueError("Knowledge graph must contain a valid 'nodes' object")

        return graph

    def _load_audit_prompt(self) -> str:
        if not self.audit_prompt_path.exists():
            raise FileNotFoundError(
                f"Audit prompt not found: {self.audit_prompt_path}"
            )
        return self.audit_prompt_path.read_text(encoding="utf-8")

    def _audit_rendered_output(
            self,
            *,
            case: EvaluationCase,
            messages: list[str],
        ) -> ScenarioRenderAudit:
            """Perform a semantic audit on rendered scenario messages using Gemini.

            Evaluates rendered text against target graph signals and non-target candidate
            nodes to verify that intended resilience concepts are present and unintended
            extraneous signals were not inadvertently leaked into the conversation.

            Args:
                case: Target EvaluationCase containing expected gold signals.
                messages: Cleaned dialogue messages generated for the scenario.

            Returns:
                ScenarioRenderAudit: Parsed validation model assessing signal alignment
                    and flagging unintended graph nodes.

            Raises:
                ValueError: If the Gemini client returns an empty text response.
            """
            target_ids = {
                signal.node_id
                for signal in case.gold.extraction.active_signals
            }

            target_nodes = [
                {
                    "node_id": signal.node_id,
                    "polarity": signal.detected_signal,
                    "name_fa": self.nodes[signal.node_id].get("name_fa", ""),
                    "description": self.nodes[signal.node_id].get("description", ""),
                }
                for signal in case.gold.extraction.active_signals
            ]

            candidates = []

            for node_id, node in self.nodes.items():
                if node_id in target_ids:
                    continue

                candidates.append(
                    {
                        "node_id": node_id,
                        "name_fa": node.get("name_fa", ""),
                        "description": node.get("description", ""),
                    }
                )

            audit_input = {
                "target_signals": target_nodes,
                "candidate_unintended_nodes": candidates,
                "messages": messages,
            }

            last_error: Exception | None = None

            for attempt in range(self.max_retries + 1):
                try:
                    if attempt == 0 and self.request_delay > 0:
                        logger.info(
                            "%s: sleeping %.1f seconds before semantic audit...",
                            case.case_id,
                            self.request_delay,
                        )
                        time.sleep(self.request_delay)

                    response = self.client.models.generate_content(
                        model=self.model_name,
                        contents=[
                            self.audit_prompt,
                            json.dumps(
                                audit_input,
                                ensure_ascii=False,
                                indent=2,
                            ),
                        ],
                        config=types.GenerateContentConfig(
                            temperature=0.0,
                            response_mime_type="application/json",
                            response_schema=ScenarioRenderAudit,
                            automatic_function_calling=types.AutomaticFunctionCallingConfig(
                                disable=True
                            ),
                        ),
                    )

                    if not response.text:
                        raise ValueError(
                            f"{case.case_id}: semantic audit returned empty response"
                        )

                    return ScenarioRenderAudit.model_validate_json(response.text)

                except Exception as exc:
                    last_error = exc

                    if attempt >= self.max_retries:
                        break

                    delay = self.retry_delay * (2**attempt)

                    logger.warning(
                        "%s: semantic audit failed on attempt %d/%d: %s. "
                        "Retrying in %.1f seconds...",
                        case.case_id,
                        attempt + 1,
                        self.max_retries + 1,
                        exc,
                        delay,
                    )

                    time.sleep(delay)

            raise RuntimeError(
                f"{case.case_id}: semantic audit failed after "
                f"{self.max_retries + 1} attempts"
            ) from last_error

    def _load_nodes(self) -> dict[str, dict[str, Any]]:
        """Retrieve node definitions from the loaded knowledge graph.

        Returns:
            dict[str, dict[str, Any]]: Mapping of node IDs to their attributes and metadata.
        """
        return self.graph["nodes"]

    def _load_prompt(self) -> str:
        """Load the rendering system prompt from disk.

        Returns:
            str: System prompt text content.

        Raises:
            FileNotFoundError: If the prompt file does not exist.
        """
        if not self.prompt_path.exists():
            raise FileNotFoundError(f"Rendering prompt not found: {self.prompt_path}")
        return self.prompt_path.read_text(encoding="utf-8")

    def _generate(self, *, prompt: str) -> ScenarioRenderOutput:
        """Generate structured scenario content with automatic retries and exponential backoff.

        Args:
            prompt: Structured JSON string representing the latent scenario spec.

        Returns:
            ScenarioRenderOutput: Structured messages and evidence output.

        Raises:
            RuntimeError: If all retry attempts fail.
        """
        last_error = None

        for attempt in range(self.max_retries + 1):
            try:
                response = self.client.models.generate_content(
                    model=self.model_name,
                    contents=[self.system_prompt, prompt],
                    config=types.GenerateContentConfig(
                        temperature=self.temperature,
                        response_mime_type="application/json",
                        response_schema=ScenarioRenderOutput,
                        automatic_function_calling=types.AutomaticFunctionCallingConfig(
                            disable=True
                        ),
                    ),
                )
                if not response.text:
                    raise ValueError("Gemini returned an empty response")

                return ScenarioRenderOutput.model_validate_json(response.text)

            except Exception as exc:
                last_error = exc
                if attempt >= self.max_retries:
                    break

                delay = self.retry_delay * (2**attempt)
                logger.warning(
                    "Gemini request failed (attempt %d/%d): %s. Retrying in %.1f seconds...",
                    attempt + 1,
                    self.max_retries + 1,
                    exc,
                    delay,
                )
                time.sleep(delay)

        raise RuntimeError(f"Gemini request failed after {self.max_retries + 1} attempts") from last_error

    def render(self, case: EvaluationCase) -> EvaluationCase:
        """Render one latent scenario into a natural-language conversation.

        Args:
            case: Evaluation case containing the latent scenario specification.

        Returns:
            EvaluationCase: Updated case with rendered messages and attached evidence.
        """
        base_prompt = self._build_user_prompt(case)
        prompt = base_prompt

        for attempt in range(self.max_retries + 1):
            try:
                rendered = self._generate(prompt=prompt)
                evidence = self._extract_evidence(case, rendered)
                messages = self._clean_messages(rendered.messages)

                self._validate_rendered_output(
                    case=case,
                    messages=messages,
                    evidence=evidence,
                )

                audit = self._audit_rendered_output(
                    case=case,
                    messages=messages,
                )

                if not audit.valid:
                    raise ValueError(
                        f"{case.case_id}: semantic audit failed: "
                        f"missing={audit.missing_target_signals}, "
                        f"unintended={audit.unintended_signal_nodes}, "
                        f"polarity={audit.polarity_errors}"
                    )

                break

            except ValueError as exc:
                if attempt >= self.max_retries:
                    raise

                delay = self.retry_delay * (2**attempt)

                logger.warning(
                    "%s: invalid rendering on attempt %d/%d: %s. "
                    "Retrying in %.1f seconds...",
                    case.case_id,
                    attempt + 1,
                    self.max_retries + 1,
                    exc,
                    delay,
                )

                time.sleep(delay)

                prompt = self._build_retry_prompt(
                    base_prompt=base_prompt,
                    error=str(exc),
                )

        case.input.messages = messages
        self._attach_evidence(
            case=case,
            evidence=evidence,
        )

        return case

    def _build_user_prompt(self, case: EvaluationCase) -> str:
        """Construct a formatted JSON prompt describing the latent scenario for the renderer.

        Aggregates target graph node signals, semantic cues, domain-confusable distractor
        nodes, and latent clinical assessment levels into a structured payload for Gemini.

        Args:
            case: Target EvaluationCase containing scenario constraints and gold signals.

        Returns:
            str: Indented JSON string representing the complete scenario rendering prompt.

        Raises:
            ValueError: If a gold active signal references a node ID missing from the graph.
        """
        active_signals = []

        target_ids = {
            signal.node_id
            for signal in case.gold.extraction.active_signals
        }

        for signal in case.gold.extraction.active_signals:
            node = self.nodes.get(signal.node_id)
            if node is None:
                raise ValueError(
                    f"{case.case_id}: unknown graph node {signal.node_id}"
                )

            cues = node.get("cues", {})

            if signal.detected_signal == "positive":
                polarity_cues = cues.get("positive_keywords", [])
            elif signal.detected_signal == "negative":
                polarity_cues = cues.get("negative_keywords", [])
            else:
                polarity_cues = (
                    cues.get("positive_keywords", [])
                    + cues.get("negative_keywords", [])
                )

            active_signals.append(
                {
                    "node_id": signal.node_id,
                    "name_fa": node.get("name_fa", ""),
                    "name_en": node.get("name_en", ""),
                    "domain_fa": node.get("domain_fa", ""),
                    "description": node.get("description", ""),
                    "polarity": signal.detected_signal,
                    "semantic_cues": polarity_cues,
                }
            )

        target_domains = {
            self.nodes[signal.node_id].get("domain")
            for signal in case.gold.extraction.active_signals
            if signal.node_id in self.nodes
        }

        confusable_nodes = []

        for node_id, node in self.nodes.items():
            if node_id in target_ids:
                continue

            if node.get("domain") not in target_domains:
                continue

            confusable_nodes.append(
                {
                    "node_id": node_id,
                    "name_fa": node.get("name_fa", ""),
                    "name_en": node.get("name_en", ""),
                    "description": node.get("description", ""),
                }
            )

        scenario = {
            "case_type": case.scenario.case_type,
            "difficulty": case.scenario.difficulty,
            "turn_count": case.scenario.turn_count,
            "safety_category": case.gold.safety.risk_category,
            "target_signals": active_signals,
            "confusable_nodes": confusable_nodes,
            "assessment_profile": {
                "severity": case.scenario.severity_level,
                "frequency": case.scenario.frequency_level,
                "functional": case.scenario.functional_level,
                "coping": case.scenario.coping_level,
            },
        }

        return json.dumps(
            scenario,
            ensure_ascii=False,
            indent=2,
        )

    def _build_retry_prompt(
        self,
        base_prompt: str,
        error: str,
    ) -> str:
        """Construct a refined retry prompt incorporating validation failure details.

        Appends the validation error message and formatting constraints to the base
        generation prompt to instruct the model to produce a valid conversation structure.

        Args:
            base_prompt: Original base generation prompt provided to the model.
            error: Validation error message or trace from the failed attempt.

        Returns:
            str: Augmented prompt string formatted for retry execution.
        """
        return (
            f"{base_prompt}\n\n"
            "=== PREVIOUS GENERATION FAILED VALIDATION ===\n"
            f"{error}\n\n"
            "Regenerate the conversation from scratch.\n"
            "Do not repeat the previous invalid structure.\n"
            "Every target signal must have exactly one evidence marker.\n"
            "Do not output multiple evidence markers for the same target node.\n"
        )

    def _clean_messages(self, messages: list[RenderedMessage]) -> list[str]:
        """Strip evidence annotation markup from rendered messages.

        Replaces evidence markup patterns with their underlying plain-text content
        to produce clean, readable user messages.

        Args:
            messages: List of RenderedMessage instances containing annotated text.

        Returns:
            list[str]: Cleaned message content strings without annotation tags.
        """
        cleaned = []

        for message in messages:
            text = EVIDENCE_PATTERN.sub(
                lambda m: m.group("text"),
                message.content,
            )
            cleaned.append(text)

        return cleaned

    def _extract_evidence(
        self, case: EvaluationCase, output: ScenarioRenderOutput
    ) -> list[dict[str, Any]]:
        """Extract evidence spans from rendered scenario messages based on regex patterns.

        Args:
            case: Target EvaluationCase instance containing gold active signals.
            output: ScenarioRenderOutput containing rendered message objects.

        Returns:
            list[dict[str, Any]]: List of extracted evidence records containing
                node_id, message_index, character span offsets, and raw text.

        Raises:
            ValueError: If an extracted evidence node_id is not part of the expected
                gold active signals for the case.
        """
        expected = {
            signal.node_id
            for signal in case.gold.extraction.active_signals
        }

        extracted = []

        for message_index, message_obj in enumerate(output.messages):
            message = message_obj.content
            cursor = 0
            clean_length = 0

            for match in EVIDENCE_PATTERN.finditer(message):
                prefix = message[cursor:match.start()]
                clean_length += len(prefix)

                node_id = match.group("node_id")
                if node_id not in expected:
                    raise ValueError(
                        f"{case.case_id}: unexpected evidence node {node_id}"
                    )

                evidence_text = match.group("text")

                if not evidence_text:
                    raise ValueError(
                        f"{case.case_id}: empty evidence for {node_id}"
                    )

                if evidence_text != evidence_text.strip():
                    raise ValueError(
                        f"{case.case_id}: evidence for {node_id} contains leading/trailing whitespace"
                    )

                start = clean_length
                clean_length += len(evidence_text)
                end = clean_length

                extracted.append(
                    {
                        "node_id": node_id,
                        "message_index": message_index,
                        "start": start,
                        "end": end,
                        "evidence": evidence_text,
                    }
                )

                cursor = match.end()

            if cursor < len(message):
                clean_length += len(message[cursor:])

        return extracted

    def _validate_rendered_output(
        self,
        *,
        case: EvaluationCase,
        messages: list[str],
        evidence: list[dict[str, Any]],
    ) -> None:
        """Validate rendered messages and extracted evidence spans against case expectations.

        Args:
            case: EvaluationCase instance containing scenario requirements and gold signals.
            messages: List of rendered user message strings.
            evidence: List of extracted evidence span dictionaries.

        Raises:
            ValueError: If message counts do not match expected turn counts, unknown signals
                are referenced, required signals lack evidence, duplicate evidence records
                are detected, message indices are out of bounds, or character offsets do not
                match the underlying message substrings.
        """
        expected_turns = case.scenario.turn_count
        if len(messages) != expected_turns:
            raise ValueError(
                f"{case.case_id}: expected {expected_turns} messages, got {len(messages)}"
            )

        signal_ids = {s.node_id for s in case.gold.extraction.active_signals}
        evidence_ids = {item["node_id"] for item in evidence}

        if unexpected := evidence_ids - signal_ids:
            raise ValueError(
                f"{case.case_id}: evidence returned for unknown signals: {sorted(unexpected)}"
            )
        if missing := signal_ids - evidence_ids:
            raise ValueError(
                f"{case.case_id}: missing evidence for signals: {sorted(missing)}"
            )
        evidence_counts = Counter(item["node_id"] for item in evidence)
        duplicates = [
            node_id
            for node_id, count in evidence_counts.items()
            if count > 1
        ]

        if duplicates:
            raise ValueError(
                f"{case.case_id}: duplicate evidence markers for nodes: "
                f"{sorted(duplicates)}"
            )

        for item in evidence:
            message_index = item["message_index"]
            if not 0 <= message_index < len(messages):
                raise ValueError(
                    f"{case.case_id}: invalid message index {message_index} for {item['node_id']}"
                )
            
            if not item["evidence"]:
                raise ValueError(
                    f"{case.case_id}: empty evidence for {item['node_id']}"
                )

            if item["evidence"] != item["evidence"].strip():
                raise ValueError(
                    f"{case.case_id}: evidence for {item['node_id']} contains "
                    "leading/trailing whitespace"
                )

            message = messages[message_index]
            if message[item["start"] : item["end"]] != item["evidence"]:
                raise ValueError(
                    f"{case.case_id}: invalid evidence span for {item['node_id']}"
                )

    def _attach_evidence(
        self,
        *,
        case: EvaluationCase,
        evidence: list[dict[str, Any]],
    ) -> None:
        """Attach validated evidence spans to their corresponding gold signals.

        Args:
            case: The evaluation case whose signals will be updated in-place.
            evidence: List of verified evidence records containing offsets and text.

        Raises:
            ValueError: If a required gold signal is missing associated evidence.
        """
        evidence_by_node = {item["node_id"]: item for item in evidence}

        for signal in case.gold.extraction.active_signals:
            item = evidence_by_node.get(signal.node_id)
            if item is None:
                raise ValueError(
                    f"{case.case_id}: missing evidence for {signal.node_id}"
                )

            signal.evidence = item["evidence"]
            signal.evidence_message_index = item["message_index"]
            signal.evidence_start = item["start"]
            signal.evidence_end = item["end"]
    def render_dataset(
        self, cases: list[EvaluationCase], *, skip_failures: bool = False
    ) -> list[EvaluationCase]:
        """Render all cases in a dataset sequentially.

        Args:
            cases: Sequence of evaluation cases to render.
            skip_failures: Whether to bypass individual failures instead of raising.

        Returns:
            list[EvaluationCase]: Successfully rendered evaluation cases.
        """
        rendered_cases = []

        for index, case in enumerate(cases, start=1):
            logger.info("Rendering case %d/%d: %s", index, len(cases), case.case_id)
            try:
                rendered_case = self.render(case)
                rendered_cases.append(rendered_case)
            except Exception:
                logger.exception("Failed to render case %s", case.case_id)
                if not skip_failures:
                    raise

            if index < len(cases):
                logger.info("Sleeping %.1f seconds before next request...", self.request_delay)
                time.sleep(self.request_delay)

        return rendered_cases


def load_cases(input_path: Path) -> list[EvaluationCase]:
    """Load evaluation scenarios from a JSONL file.

    Args:
        input_path: Path to the JSONL input file.

    Returns:
        list[EvaluationCase]: Parsed evaluation cases.

    Raises:
        FileNotFoundError: If the input file is missing.
        ValueError: If line deserialization or schema validation fails.
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Input dataset not found: {input_path}")

    cases: list[EvaluationCase] = []
    with input_path.open("r", encoding="utf-8") as file:
        for line_number, line in enumerate(file, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                cases.append(EvaluationCase.model_validate(json.loads(line)))
            except Exception as exc:
                raise ValueError(f"Invalid evaluation case at line {line_number}: {exc}") from exc

    return cases


def write_cases(cases: list[EvaluationCase], output_path: Path) -> None:
    """Write rendered evaluation cases to a JSONL file.

    Args:
        cases: Sequence of evaluation cases to write.
        output_path: Destination path for the JSONL file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8") as file:
        for case in cases:
            file.write(json.dumps(case.model_dump(), ensure_ascii=False) + "\n")


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments for the scenario renderer.

    Returns:
        argparse.Namespace: Parsed CLI argument namespace.
    """
    parser = argparse.ArgumentParser(
        description="Render latent ResiliMind evaluation scenarios into natural-language Persian conversations."
    )
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT_PATH, help="Path to the latent scenarios JSONL file.")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_PATH, help="Path for the rendered cases JSONL file.")
    parser.add_argument("--model", type=str, default=os.getenv("GEMINI_MODEL", "gemini-2.5-flash"), help="Gemini model used for scenario rendering.")
    parser.add_argument("--temperature", type=float, default=0.4, help="Sampling temperature.")
    parser.add_argument("--prompt", type=Path, default=DEFAULT_PROMPT_PATH, help="Path to the rendering system prompt.")
    parser.add_argument("--audit-prompt", type=Path, default=DEFAULT_AUDIT_PROMPT_PATH, help="Path to the semantic audit prompt.")
    parser.add_argument("--limit", type=int, default=None, help="Render only the first N cases.")
    parser.add_argument("--skip-failures", action="store_true", help="Skip cases that fail rendering.")
    parser.add_argument("--max-retries", type=int, default=3, help="Maximum number of retries after an API failure.")
    parser.add_argument("--retry-delay", type=float, default=2.0, help="Initial retry delay in seconds.")
    parser.add_argument("--request-delay", type=float, default=1.0, help="Delay between consecutive API requests in seconds.")
    return parser.parse_args()


def main() -> None:
    """Run the complete scenario rendering pipeline."""
    load_dotenv()
    args = parse_args()

    cases = load_cases(args.input)
    if args.limit is not None:
        if args.limit <= 0:
            raise ValueError("--limit must be greater than zero")
        cases = cases[:args.limit]

    renderer = ScenarioRenderer(
        model_name=args.model,
        temperature=args.temperature,
        prompt_path=args.prompt,
        max_retries=args.max_retries,
        retry_delay=args.retry_delay,
        request_delay=args.request_delay,
    )

    rendered_cases = renderer.render_dataset(cases, skip_failures=args.skip_failures)
    with GRAPH_PATH.open("r", encoding="utf-8") as file:
        graph = json.load(file)

    valid_node_ids = set(graph["nodes"].keys())

    errors = validate_dataset(
        cases,
        valid_node_ids=valid_node_ids,
        require_rendered=True,
    )
    if errors:
        formatted_errors = "\n".join(f"- {error}" for error in errors)
        raise ValueError(
            f"Rendered dataset validation failed:\n{formatted_errors}"
        )
    
    write_cases(rendered_cases, args.output)

    print(f"Rendered {len(rendered_cases)} cases.")
    print(f"Dataset: {args.output}")
    print(f"Model: {args.model}")


if __name__ == "__main__":
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )
    main()
